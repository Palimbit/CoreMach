#include "cpu_808x_test_harness.h"

#include <assert.h>
#include <stdint.h>

int
main(void)
{
    static const uint8_t program[] = {
        0xb0, 0x81, 0xd0, 0xc0, 0xa2, 0x00, 0x02, /* ROL AL,1 -> 03 */
        0xb0, 0x01, 0xd0, 0xc8, 0xa2, 0x01, 0x02, /* ROR AL,1 -> 80 */
        0xf8, 0xb0, 0x80, 0xd0, 0xd0, 0xa2, 0x02, 0x02, /* RCL -> 00, CF=1 */
        0xf9, 0xb0, 0x00, 0xd0, 0xd8, 0xa2, 0x03, 0x02, /* RCR -> 80 */
        0xb0, 0x81, 0xd0, 0xe0, 0xa2, 0x04, 0x02, /* SHL -> 02 */
        0xb0, 0x81, 0xd0, 0xe8, 0xa2, 0x05, 0x02, /* SHR -> 40 */
        0xb0, 0x81, 0xd0, 0xf0, 0xa2, 0x06, 0x02, /* SAL alias -> 02 */
        0xb0, 0x81, 0xd0, 0xf8, 0xa2, 0x07, 0x02, /* SAR -> C0 */
        0xb1, 0x02, 0xb0, 0x81, 0xd2, 0xc0, 0xa2, 0x08, 0x02,
        0xb8, 0x01, 0x80, 0xd1, 0xc8, 0xa3, 0x0a, 0x02,
        0xb1, 0x04, 0xb8, 0x00, 0xf0, 0xd3, 0xf8, 0xa3, 0x0c, 0x02,
        0xb8, 0x55, 0xaa, 0xbb, 0x0f, 0x0f, 0x85, 0xd8, 0x84, 0xd8,
        0xb8, 0x00, 0x10, 0xb9, 0x01, 0x10, 0xba, 0x02, 0x10,
        0xbb, 0x03, 0x10, 0xbc, 0x04, 0x10, 0xbd, 0x05, 0x10,
        0xbe, 0x06, 0x10, 0xbf, 0x07, 0x10,
        0x91, 0x92, 0x93, 0x94, 0x95, 0x96, 0x97,
        0xf4
    };
    cpu_808x_test_machine_t machine;

    cpu_808x_test_machine_create(&machine, NULL, program, sizeof(program));
    assert(cpu_808x_test_run(&machine, 100U) == BM_STATUS_OK);
    assert(cpu_808x_test_inspect(&machine, "halted") == 1U);
    assert(cpu_808x_test_peek(&machine, 0x0200U) == 0x03U);
    assert(cpu_808x_test_peek(&machine, 0x0201U) == 0x80U);
    assert(cpu_808x_test_peek(&machine, 0x0202U) == 0x00U);
    assert(cpu_808x_test_peek(&machine, 0x0203U) == 0x80U);
    assert(cpu_808x_test_peek(&machine, 0x0204U) == 0x02U);
    assert(cpu_808x_test_peek(&machine, 0x0205U) == 0x40U);
    assert(cpu_808x_test_peek(&machine, 0x0206U) == 0x02U);
    assert(cpu_808x_test_peek(&machine, 0x0207U) == 0xc0U);
    assert(cpu_808x_test_peek(&machine, 0x0208U) == 0x06U);
    assert(cpu_808x_test_peek(&machine, 0x020aU) == 0x00U &&
           cpu_808x_test_peek(&machine, 0x020bU) == 0xc0U);
    assert(cpu_808x_test_peek(&machine, 0x020cU) == 0x00U &&
           cpu_808x_test_peek(&machine, 0x020dU) == 0xffU);
    assert((cpu_808x_test_inspect(&machine, "flags") & 0x0045U) == 0x0004U);
    assert(cpu_808x_test_inspect(&machine, "ax") == 0x1007U);
    assert(cpu_808x_test_inspect(&machine, "cx") == 0x1000U);
    assert(cpu_808x_test_inspect(&machine, "dx") == 0x1001U);
    assert(cpu_808x_test_inspect(&machine, "bx") == 0x1002U);
    assert(cpu_808x_test_inspect(&machine, "sp") == 0x1003U);
    assert(cpu_808x_test_inspect(&machine, "bp") == 0x1004U);
    assert(cpu_808x_test_inspect(&machine, "si") == 0x1005U);
    assert(cpu_808x_test_inspect(&machine, "di") == 0x1006U);

    cpu_808x_test_machine_destroy(&machine);
    return 0;
}
